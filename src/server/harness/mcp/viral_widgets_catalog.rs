//! Structured catalog of supported OneHumanCorp viral growth widgets.

use serde::{Deserialize, Serialize};
use serde_json::{Value, json};

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum EmbedKind {
    Iframe,
    Script,
    Image,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum ParamRule {
    Text { max_len: usize },
    Code { max_len: usize },
    HexColor,
    HttpsUrl { max_len: usize },
    Integer { min: i64, max: i64 },
    Boolean,
    Enum(&'static [&'static str]),
}

#[derive(Debug, Clone)]
pub(crate) struct ParamSpec {
    pub(crate) name: &'static str,
    pub(crate) query_key: &'static str,
    pub(crate) description: &'static str,
    pub(crate) required: bool,
    pub(crate) rule: ParamRule,
    pub(crate) default: Value,
}

#[derive(Debug, Clone)]
pub(crate) struct WidgetSpec {
    pub(crate) id: &'static str,
    pub(crate) name: &'static str,
    pub(crate) category: &'static str,
    pub(crate) description: &'static str,
    pub(crate) embed_kind: EmbedKind,
    pub(crate) builder_route: &'static str,
    pub(crate) embed_endpoint: &'static str,
    pub(crate) default_width: u16,
    pub(crate) default_height: u16,
    pub(crate) standing_authority_note: &'static str,
    pub(crate) params: Vec<ParamSpec>,
    pub(crate) presets: Vec<Value>,
}

fn p(
    name: &'static str,
    query_key: &'static str,
    description: &'static str,
    required: bool,
    rule: ParamRule,
    default: Value,
) -> ParamSpec {
    ParamSpec {
        name,
        query_key,
        description,
        required,
        rule,
        default,
    }
}

#[allow(clippy::too_many_arguments)]
fn w(
    id: &'static str,
    name: &'static str,
    category: &'static str,
    description: &'static str,
    embed_kind: EmbedKind,
    builder_route: &'static str,
    embed_endpoint: &'static str,
    dims: (u16, u16),
    standing_authority_note: &'static str,
    params: Vec<ParamSpec>,
    presets: Vec<Value>,
) -> WidgetSpec {
    WidgetSpec {
        id,
        name,
        category,
        description,
        embed_kind,
        builder_route,
        embed_endpoint,
        default_width: dims.0,
        default_height: dims.1,
        standing_authority_note,
        params,
        presets,
    }
}

